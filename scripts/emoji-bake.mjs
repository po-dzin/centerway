#!/usr/bin/env node
/**
 * Bakes the CenterWay reaction emoji into a shipped sprite.
 *
 * Source: scripts/lib/emoji-glyphs.mjs (drawings, palette, detail gate).
 * Emits:
 *   public/cw/emoji/cw-emoji.svg   one <symbol id="cwe-<id>" viewBox="0 0 48 48">
 *                                  per emoji, referenced as <use href="…#cwe-joy">
 *   src/lib/brand/emojiSet.ts      the ordered list ({ id, name, group }), the id
 *                                  union and the sprite's content hash
 *
 * WHY OUR OWN SVG AND NOT THE SYSTEM'S EMOJI. A reaction drawn by the OS is a
 * different picture on every phone, in a palette no stylesheet reaches. Serving
 * the set ourselves makes the feed look the same everywhere and keeps the
 * drawing on the brand's line.
 *
 * THE DETAIL GATE FAILS THE BAKE. An emoji that breaks it (too many parts, a dot
 * or a stroke that will not survive 20px, too many colours) is refused here, by
 * name, before anything is written — the same way the icon contract is held.
 *
 * Like icons-bake, a write never drops a symbol by accident: once an id ships,
 * a stored reaction can point at it, so removing one needs `--allow-drop`.
 *
 * Usage:
 *   node scripts/emoji-bake.mjs                 # gate, then write the sprite and the list
 *   node scripts/emoji-bake.mjs --check         # gate, then fail if output differs from disk
 *   node scripts/emoji-bake.mjs --allow-drop    # write even if a symbol disappears
 */

import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import process from "node:process";
import { EMOJI, VIEWBOX, drawEmoji, gateFailures } from "./lib/emoji-glyphs.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const SPRITE_TARGET = path.join(ROOT, "public/cw/emoji/cw-emoji.svg");
const SET_TARGET = path.join(ROOT, "src/lib/brand/emojiSet.ts");

function parseArgs(argv) {
  const args = { check: false, allowDrop: false };
  for (const arg of argv.slice(2)) {
    if (arg === "--check") args.check = true;
    else if (arg === "--allow-drop") args.allowDrop = true;
    else throw new Error(`unknown argument: ${arg}`);
  }
  return args;
}

function bake() {
  const failures = [];
  const ids = new Set();
  const symbols = [];
  for (const entry of EMOJI) {
    if (!/^[a-z][a-z0-9-]*$/.test(entry.id)) failures.push(`${entry.id}: id is not a lowercase ASCII slug`);
    if (ids.has(entry.id)) failures.push(`${entry.id}: duplicate id`);
    ids.add(entry.id);
    const { parts, meta } = drawEmoji(entry);
    const bad = gateFailures(meta);
    if (bad.length) failures.push(`${entry.id} (${entry.name}): ${bad.join("; ")}`);
    symbols.push(
      `  <symbol id="cwe-${entry.id}" viewBox="${VIEWBOX}">\n` +
        parts.map((part) => `    ${part}\n`).join("") +
        `  </symbol>\n`,
    );
  }
  const sprite =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- GENERATED by scripts/emoji-bake.mjs — do not edit.\n` +
    `     Source: scripts/lib/emoji-glyphs.mjs -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n` +
    symbols.join("") +
    `</svg>\n`;
  return { sprite, failures };
}

/** Same reasoning as CW_SPRITE_VERSION in scripts/icons-bake.mjs: the sprite is referenced by id. */
const spriteVersion = (sprite) => crypto.createHash("sha256").update(sprite).digest("hex").slice(0, 8);

function setModule(sprite) {
  const rows = EMOJI.map(
    (e) => `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.name)}, group: ${JSON.stringify(e.group)} },`,
  ).join("\n");
  return `// GENERATED by scripts/emoji-bake.mjs — do not edit.
// Source: scripts/lib/emoji-glyphs.mjs

// Cache key for the sprite URL — see spriteVersion() in scripts/icons-bake.mjs.
export const CW_EMOJI_SPRITE_VERSION = "${spriteVersion(sprite)}";

export const CW_EMOJI_SPRITE_URL = \`/cw/emoji/cw-emoji.svg?v=\${CW_EMOJI_SPRITE_VERSION}\`;

/** The reaction set in picker order. The sprite symbol of each is \`cwe-<id>\`. */
export const CW_EMOJI = [
${rows}
] as const;

export type CwEmojiId = (typeof CW_EMOJI)[number]["id"];
export type CwEmojiGroup = (typeof CW_EMOJI)[number]["group"];
`;
}

const symbolIds = (svg) => new Set([...svg.matchAll(/<symbol id="([^"]+)"/g)].map((match) => match[1]));

async function main() {
  const args = parseArgs(process.argv);
  const { sprite, failures } = bake();

  if (failures.length) {
    console.error(`emoji detail gate: FAIL\n  ${failures.join("\n  ")}`);
    console.error("See GATE in scripts/lib/emoji-glyphs.mjs: an emoji is read at 20px in a reaction chip.");
    process.exit(1);
  }

  if (!args.check && !args.allowDrop) {
    const existing = await fs.readFile(SPRITE_TARGET, "utf8").catch(() => null);
    if (existing) {
      const baked = symbolIds(sprite);
      const dropped = [...symbolIds(existing)].filter((id) => !baked.has(id)).sort();
      if (dropped.length) {
        console.error(
          `refusing to write: the bake would remove ${dropped.length} emoji the sprite ships — ${dropped.join(", ")}.\n` +
            "A stored reaction may point at it. Re-run with --allow-drop if the removal is intended.",
        );
        process.exit(1);
      }
    }
  }

  const outputs = [
    { target: SPRITE_TARGET, content: sprite },
    { target: SET_TARGET, content: setModule(sprite) },
  ];

  let drift = false;
  for (const { target, content } of outputs) {
    const existing = await fs.readFile(target, "utf8").catch(() => null);
    if (existing === content) continue;
    if (args.check) {
      drift = true;
      console.error(`drift: ${path.relative(ROOT, target)} does not match the baked output`);
      continue;
    }
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content);
    console.log(`wrote ${path.relative(ROOT, target)}`);
  }

  if (args.check) {
    if (drift) process.exit(1);
    console.log(`emoji:check ok — ${EMOJI.length} emoji, detail gate passed`);
  } else {
    console.log(`baked ${EMOJI.length} emoji, detail gate passed`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
