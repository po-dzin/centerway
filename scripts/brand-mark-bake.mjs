#!/usr/bin/env node
/**
 * Bakes the F2 brand mark into the shipped SVG files.
 *
 * WHY A BAKE STEP
 * The mark has one source of truth — data/brand/cw-mark-f2.json, lifted from
 * the approved LogoMark in the Claude Design system. Everything that paints it
 * (platform header, footer, five landing navs, the favicon) has to come off
 * that one geometry, or the marks drift apart the way the two old PNGs did:
 * cw-logo-ink.png was a 256px canvas inset to 78.5%, cw-logo-gold.png a 128px
 * canvas filled edge to edge, and network-tokens.css carried a hand-measured
 * 10.75% padding to make them look the same size. Baked from one viewBox, that
 * compensation stops existing.
 *
 * WHAT IT EMITS
 *   cw-mark.svg          shape only, black fill — consumed as a CSS mask, so
 *                        the platform tone flip is a background-color change
 *                        rather than the old brightness(0) filter hack.
 *   cw-mark-compact.svg  the 20-24px build (two arcs, wider gaps, floored
 *                        weight) — same treatment.
 *   cw-mark-{ink,gold}.svg  pre-coloured, for the static landings, which paint
 *                        the mark through <img> and cannot inherit a colour.
 *   icon.svg             the favicon: compact build, gold on the deep ground.
 *   favicon.ico          the same, rasterised — Safari only learned SVG
 *                        favicons in 17.
 *   apple-icon.png       180px touch icon, flattened: iOS composites a
 *                        transparent one onto black.
 *
 * The animated states cannot be baked into a flat file: they need one element
 * per arc plus a stroked mask. So the geometry is also emitted as a TS module
 * (src/components/brand/markGeometry.ts) that LogoMark renders from — same
 * source, no second copy of the path data to keep in step.
 *
 * Usage:
 *   node scripts/brand-mark-bake.mjs           # write the files
 *   node scripts/brand-mark-bake.mjs --check   # fail if output differs on disk
 */

import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const GEOMETRY = path.join(ROOT, "data/brand/cw-mark-f2.json");
const TOKENS = path.join(ROOT, "data/design-tokens/cw.tokens.json");
const WORDMARK_GOLD = path.join(ROOT, "public/cw/brand/cw-wordmark-light.svg");

/** Which token each shipped tone is drawn from, so the files cannot drift off the palette. */
const TONES = {
  ink: "--cw-sem-guide-strong",
  gold: "--cw-sem-warmth",
  calm: "--cw-sem-calm-bg",
};

const BANNER = "GENERATED by scripts/brand-mark-bake.mjs — do not edit. Source: data/brand/cw-mark-f2.json";

function readToken(tokens, name) {
  const found = [];
  const walk = (node) => {
    if (!node || typeof node !== "object") return;
    for (const [key, value] of Object.entries(node)) {
      if (key === name && typeof value === "string") found.push(value);
      else walk(value);
    }
  };
  walk(tokens);
  if (found.length === 0) throw new Error(`token ${name} not found in ${path.relative(ROOT, TOKENS)}`);
  return found[0];
}

/**
 * The static mark is the filled brush outlines plus the core. No stroke, no
 * currentColor when a fill is given: the landings load these through <img>,
 * where currentColor resolves to black and the tone would be lost.
 */
function markSvg(build, { fill, size }) {
  const paths = build.arcs.map((d) => `  <path d="${d}"/>`).join("\n");
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${size}" height="${size}" fill="${fill}">`,
    `  <!-- ${BANNER} -->`,
    paths,
    `  <circle cx="32" cy="32" r="${build.coreR}"/>`,
    `</svg>`,
    ``,
  ].join("\n");
}

/**
 * Emitted rather than imported: a JSON import would ship the `mids` paths to
 * every page that renders a static mark, and they are only read by the draw
 * animation. Two exported consts let the bundler drop what a route never uses.
 */
function geometryModule(geometry) {
  const build = (name, data) => [
    `export const ${name}: MarkBuild = {`,
    `  arcs: [`,
    ...data.arcs.map((d) => `    "${d}",`),
    `  ],`,
    `  mids: [`,
    ...data.mids.map((d) => `    "${d}",`),
    `  ],`,
    `  lens: [${data.lens.join(", ")}],`,
    `  coreR: ${data.coreR},`,
    `};`,
  ].join("\n");

  return [
    `// ${BANNER}`,
    ``,
    `/**`,
    ` * F2 brand mark geometry. viewBox 0 0 64 64.`,
    ` *`,
    ` * arcs — filled brush outlines, the mark as it rests.`,
    ` * mids — the same three strokes as centrelines. Only the draw animation`,
    ` *        reads them: stroked at width 9 inside a mask, they wipe the arcs`,
    ` *        in. Drawing the outlines themselves cannot work — a variable-width`,
    ` *        outline has no single dash direction to run along.`,
    ` * lens — path length of each centreline, the dasharray/dashoffset seed.`,
    ` */`,
    `export type MarkBuild = {`,
    `  arcs: readonly string[];`,
    `  mids: readonly string[];`,
    `  lens: readonly number[];`,
    `  coreR: number;`,
    `};`,
    ``,
    build("FULL", geometry.full),
    ``,
    `/** 20-24px build: two arcs, 86-degree gaps, floored weight. Below 20px the mark is not used. */`,
    build("COMPACT", geometry.compact),
    ``,
  ].join("\n");
}

/**
 * App icon. Padded to a safe zone rather than filling the square: Android crops
 * a maskable icon to whatever shape the launcher wants (circle, squircle,
 * teardrop) and only the middle 80% is guaranteed to survive. `inset` is the
 * fraction of the canvas the mark is allowed to occupy.
 */
function appIconSvg(build, { fill, background, inset }) {
  const offset = (64 - 64 * inset) / 2;
  const paths = build.arcs.map((d) => `    <path d="${d}"/>`).join("\n");
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="512" height="512">`,
    `  <!-- ${BANNER} -->`,
    `  <rect width="64" height="64" fill="${background}"/>`,
    `  <g fill="${fill}" transform="translate(${offset.toFixed(3)} ${offset.toFixed(3)}) scale(${inset})">`,
    paths,
    `    <circle cx="32" cy="32" r="${build.coreR}"/>`,
    `  </g>`,
    `</svg>`,
    ``,
  ].join("\n");
}

/**
 * The link-preview card, 1200x630. Gold on the deep ground rather than ink on
 * cream: a preview lands inside someone else's chat or feed, on a surface we do
 * not control, and the dark card holds its edges against both.
 *
 * The wordmark is inlined as the outlined paths the shipped file already
 * carries, so the card needs no font at bake time and cannot come out different
 * on a machine with a different fontconfig.
 */
function ogCardSvg(build, { mark, background, wordmarkInner, wordmarkViewBox }) {
  const paths = build.arcs.map((d) => `    <path d="${d}"/>`).join("\n");
  const markSize = 190;
  const wordWidth = 470;
  const wordHeight = wordWidth * (129.3 / 541.3);
  // Optically centred: the group runs markTop..wordmark bottom, so the top
  // margin is smaller than the bottom one by half the wordmark block.
  const markTop = 138;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630" width="1200" height="630">`,
    `  <!-- ${BANNER} -->`,
    `  <rect width="1200" height="630" fill="${background}"/>`,
    `  <g fill="${mark}" transform="translate(${600 - markSize / 2} ${markTop}) scale(${markSize / 64})">`,
    paths,
    `    <circle cx="32" cy="32" r="${build.coreR}"/>`,
    `  </g>`,
    `  <svg x="${600 - wordWidth / 2}" y="${markTop + markSize + 52}" width="${wordWidth}" height="${wordHeight.toFixed(2)}" viewBox="${wordmarkViewBox}">`,
    wordmarkInner,
    `  </svg>`,
    `</svg>`,
    ``,
  ].join("\n");
}

/**
 * Flattened onto the calm ground — see the call site for why nothing here is
 * transparent. ensureAlpha still matters after the flatten: Next's ICO decoder
 * rejects an embedded PNG that is not RGBA, and sharp would otherwise drop the
 * now-opaque alpha channel and emit RGB.
 */
async function rasterise(svg, size, background) {
  return sharp(svg, { density: 600 })
    .resize(size, size)
    .flatten({ background })
    .ensureAlpha()
    .png({ compressionLevel: 9, palette: false })
    .toBuffer();
}

/**
 * Wraps a PNG in an ICO container. The format allows a PNG payload verbatim, so
 * this is a 6-byte header plus one 16-byte directory entry — cheaper than a
 * dependency, and it keeps the favicon on the same bake as everything else.
 */
function toIco(png) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(1, 4); // one image
  const entry = Buffer.alloc(16);
  entry.writeUInt8(64, 0); // width  (0 would mean 256; 64 is written literally)
  entry.writeUInt8(64, 1); // height
  entry.writeUInt8(0, 2); // palette size
  entry.writeUInt8(0, 3); // reserved
  entry.writeUInt16LE(1, 4); // colour planes
  entry.writeUInt16LE(32, 6); // bits per pixel
  entry.writeUInt32LE(png.length, 8);
  entry.writeUInt32LE(header.length + entry.length, 12);
  return Buffer.concat([header, entry, png]);
}

async function main() {
  const check = process.argv.includes("--check");
  const unknown = process.argv.slice(2).filter((a) => a !== "--check");
  if (unknown.length) throw new Error(`unknown argument: ${unknown[0]}`);

  const geometry = JSON.parse(await fs.readFile(GEOMETRY, "utf8"));
  const tokens = JSON.parse(await fs.readFile(TOKENS, "utf8"));
  const ink = readToken(tokens, TONES.ink);
  const gold = readToken(tokens, TONES.gold);

  const files = new Map();
  const emit = (relPaths, contents) => {
    for (const rel of relPaths) files.set(rel, contents);
  };

  // Mask sources — alpha is all the mask reads, so the fill is only a placeholder.
  emit(["public/cw/brand/cw-mark.svg"], markSvg(geometry.full, { fill: "#000", size: 64 }));
  emit(["public/cw/brand/cw-mark-compact.svg"], markSvg(geometry.compact, { fill: "#000", size: 64 }));

  // Pre-coloured, for <img> consumers: the platform footer and every landing nav.
  for (const [tone, colour] of [["ink", ink], ["gold", gold]]) {
    emit(
      [`public/cw/brand/cw-mark-${tone}.svg`, `src/landing-static/shared/img/cw-mark-${tone}.svg`],
      markSvg(geometry.full, { fill: colour, size: 64 }),
    );
  }

  // Favicon. Compact build: a tab icon renders at 16-32px, which is exactly the
  // range the full mark's turns collapse in.
  //
  // Gold on the deep ground, not ink on cream (2026-08-20). The old pairing
  // measured 12.09 and still disappeared in a tab strip: at 16px the contrast
  // that matters is the tile against the browser's own chrome, and a cream tile
  // on a light strip has none. A dark tile carries in both browser themes, and
  // gold on it measures 6.92. Gold on cream is not the alternative — that pair
  // is 1.75.

  // The animated component's geometry.
  emit(["src/components/brand/markGeometry.ts"], geometryModule(geometry));

  // Raster fallbacks. Safari only learned SVG favicons in 17, and an Apple touch
  // icon is composited onto black when it ships transparent — so both get the
  // calm ground painted in rather than an alpha channel.
  const calm = readToken(tokens, TONES.calm);
  // The tab icon, in both formats browsers ask for. `inset` is looser than the
  // app icons' because nothing crops a favicon — the mark just needs air.
  const tabIcon = appIconSvg(geometry.compact, { fill: gold, background: ink, inset: 0.72 });
  emit(["src/app/icon.svg"], tabIcon);
  emit(["src/app/favicon.ico"], toIco(await rasterise(Buffer.from(tabIcon), 64, ink)));
  const rasterSource = Buffer.from(markSvg(geometry.compact, { fill: ink, size: 64 }));
  emit(["src/app/apple-icon.png"], await rasterise(rasterSource, 180, calm));

  // Installed-app icons. `any` fills the square because desktop launchers and
  // the browser tab strip draw it as-is; `maskable` keeps the mark inside the
  // 80% safe zone because Android crops it to the launcher's own shape.
  const iconAny = Buffer.from(appIconSvg(geometry.full, { fill: ink, background: calm, inset: 0.9 }));
  const iconMaskable = Buffer.from(appIconSvg(geometry.full, { fill: ink, background: calm, inset: 0.62 }));
  // Mirrored into shared/img as well: the funnel hosts cannot see /cw/**, and a
  // landing still needs a raster favicon for the browsers without SVG support.
  emit(["public/cw/brand/cw-icon-192.png", "src/landing-static/shared/img/cw-icon-192.png"], await rasterise(iconAny, 192, calm));
  emit(["src/landing-static/shared/img/cw-apple-touch.png"], await rasterise(rasterSource, 180, calm));
  emit(["public/cw/brand/cw-icon-512.png"], await rasterise(iconAny, 512, calm));
  emit(["public/cw/brand/cw-icon-maskable-512.png"], await rasterise(iconMaskable, 512, calm));

  // Link preview. Also mirrored into shared/img so the funnel hosts, which
  // cannot see /cw/**, can point og:image at their own origin.
  const wordmark = await fs.readFile(WORDMARK_GOLD, "utf8");
  const wordmarkInner = wordmark.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  const wordmarkViewBox = /viewBox="([^"]+)"/.exec(wordmark)[1];
  const ogSource = Buffer.from(
    ogCardSvg(geometry.full, { mark: gold, background: ink, wordmarkInner, wordmarkViewBox }),
  );
  // density oversamples the curves, then resize brings it back to the 1200x630
  // the scrapers actually want — rasterising at 1:1 leaves the arc edges chewed.
  const ogPng = await sharp(ogSource, { density: 300 })
    .resize(1200, 630)
    .png({ compressionLevel: 9 })
    .toBuffer();
  emit(["public/cw/brand/cw-og-cover.png", "src/landing-static/shared/img/cw-og-cover.png"], ogPng);

  let failed = 0;
  for (const [rel, contents] of files) {
    const abs = path.join(ROOT, rel);
    const binary = Buffer.isBuffer(contents);
    if (check) {
      const onDisk = await fs.readFile(abs, binary ? undefined : "utf8").catch(() => null);
      const same = binary ? onDisk !== null && Buffer.compare(onDisk, contents) === 0 : onDisk === contents;
      if (!same) {
        console.error(`brand-mark-bake: ${rel} is stale`);
        failed += 1;
      }
      continue;
    }
    await fs.mkdir(path.dirname(abs), { recursive: true });
    await fs.writeFile(abs, contents);
    console.log(`brand-mark-bake: wrote ${rel}`);
  }

  if (failed) {
    console.error(`brand-mark-bake: ${failed} file(s) stale — run "npm run brand:build"`);
    process.exitCode = 1;
  } else if (check) {
    console.log(`brand-mark-bake: ${files.size} file(s) up to date`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
