/**
 * Measuring retrieval against questions somebody actually asked.
 *
 * WHAT IS BEING MEASURED, PRECISELY: given a question and the corpus, does the
 * document that answers it appear in the first `k` hits? Nothing here judges an
 * ANSWER — there is no model in this contour yet, and there does not need to be
 * one for this number to be useful. Retrieval is the half that fails silently:
 * a model handed the wrong document writes a confident, well-worded, wrong
 * paragraph, and no amount of prompt work fixes a document that was never
 * fetched.
 *
 * RECALL AT K, NOT PRECISION. The assistant will be given several documents and
 * asked to answer from them, so a right document in third place is a success;
 * an irrelevant document in first place costs tokens, not correctness. The one
 * number worth watching is how often the right document is absent entirely.
 *
 * THE LABELS COME FROM PEOPLE. A case says which document SHOULD answer, and a
 * person decides that by reading. Labels generated by the retrieval being
 * measured would make this a test that the code equals itself.
 */

import { search, type KnowledgeIndex } from "./search";

export type EvalCase = {
  question: string;
  /** Corpus id that should answer it, e.g. "support:where-course". */
  expectedDocId: string;
  /** Where the question came from — a real capture, or a seed written by hand. */
  origin?: string;
};

export type EvalMiss = {
  question: string;
  expectedDocId: string;
  /** What retrieval returned instead, best first. */
  got: string[];
};

export type EvalReport = {
  total: number;
  hits: number;
  /** Hits ÷ total, or 1 when there is nothing to measure yet. */
  recall: number;
  /** Where in the result list the right document landed, when it landed. */
  ranks: number[];
  misses: EvalMiss[];
  /** Cases naming a document the corpus does not contain — a stale label. */
  unknownExpectations: string[];
};

export function evaluateRetrieval(
  index: KnowledgeIndex,
  cases: EvalCase[],
  options: { k?: number; audience?: "public" | "learner" } = {}
): EvalReport {
  const k = options.k ?? 5;
  const known = new Set(index.docs.map((doc) => doc.id));

  const report: EvalReport = { total: 0, hits: 0, recall: 1, ranks: [], misses: [], unknownExpectations: [] };

  for (const testCase of cases) {
    // A label pointing at a document that no longer exists is not a failure of
    // retrieval — it is a failure of the label, and counting it as a miss would
    // send somebody looking for a bug in the wrong module.
    if (!known.has(testCase.expectedDocId)) {
      report.unknownExpectations.push(`${testCase.expectedDocId} (${testCase.question})`);
      continue;
    }

    report.total += 1;
    const got = search(index, testCase.question, { limit: k, audience: options.audience }).map((hit) => hit.doc.id);
    const rank = got.indexOf(testCase.expectedDocId);

    if (rank >= 0) {
      report.hits += 1;
      report.ranks.push(rank + 1);
    } else {
      report.misses.push({ question: testCase.question, expectedDocId: testCase.expectedDocId, got });
    }
  }

  report.recall = report.total === 0 ? 1 : report.hits / report.total;
  return report;
}

/** One line for a terminal or a CI log. */
export function formatReport(report: EvalReport, k: number): string {
  const percent = (report.recall * 100).toFixed(0);
  const meanRank = report.ranks.length
    ? (report.ranks.reduce((sum, rank) => sum + rank, 0) / report.ranks.length).toFixed(2)
    : "—";
  return `recall@${k} ${percent}% (${report.hits}/${report.total}), середній ранг ${meanRank}, промахів ${report.misses.length}`;
}
